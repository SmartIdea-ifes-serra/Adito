SET search_path TO unificado, public;

-- ----------------------------------------------------------------------------
-- 1. CLASSES DE ASSOCIACAO E ASSOCIATIVE DO MODELO (Possuem ID proprio)
-- ----------------------------------------------------------------------------

-- Classe de Associacao: ParceriaGrupo (GrupoPesquisaCNPQ 1..* -- 1..* InstituicaoParceiraCNPQ)
CREATE TABLE unificado.parceria_grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE,
    id_instituicao_parceira BIGINT NOT NULL REFERENCES unificado.instituicao_parceira_cnpq(id) ON DELETE CASCADE,
    tipo TEXT
);

-- Classe de Associacao: MembroProjeto (PessoaLattes 0..* -- 0..* ProjetoLATTES)
CREATE TABLE unificado.membro_projeto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE,
    id_projeto_lattes BIGINT NOT NULL REFERENCES unificado.projeto_lattes(id) ON DELETE CASCADE,
    papel unificado.tipo_papel_projeto
);

-- Classe de Associacao: FomentoProjeto (Organizacao fomento 0..* -- 0..* ProjetoLATTES)
CREATE TABLE unificado.fomento_projeto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organizacao BIGINT NOT NULL REFERENCES unificado.organizacao(id) ON DELETE CASCADE,
    id_projeto_lattes BIGINT NOT NULL REFERENCES unificado.projeto_lattes(id) ON DELETE CASCADE,
    id_tipo_apoio BIGINT REFERENCES unificado.tipo_apoio_financiamento(id)
);

-- Classe <<associative>>: ParticipacaoEvento (PessoaLattes 1 -- 1..* EventoCientifico)
CREATE TABLE unificado.participacao_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE,
    id_evento_cientifico BIGINT NOT NULL REFERENCES unificado.evento_cientifico(id) ON DELETE CASCADE,
    papel_evento unificado.tipo_papel_evento,
    titulo_apresentacao TEXT
);

-- Classe <<associative>>: ProficienciaIdioma (PessoaLattes 1 -- 0..* Idioma)
CREATE TABLE unificado.proficiencia_idioma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE,
    id_idioma BIGINT NOT NULL REFERENCES unificado.idioma(id) ON DELETE CASCADE,
    compreende unificado.tipo_nivel_proficiencia,
    fala unificado.tipo_nivel_proficiencia,
    le unificado.tipo_nivel_proficiencia,
    escreve unificado.tipo_nivel_proficiencia
);

-- ----------------------------------------------------------------------------
-- 2. TABELAS DE JUNCAO PURAS N:N (Sem ID proprio, PK composta por FKs)
-- ----------------------------------------------------------------------------

-- A04: PessoaLattes [0..*] -- Titulacao [0..*]
