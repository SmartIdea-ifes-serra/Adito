-- Classe BancaExaminadora
CREATE TABLE unificado.banca_examinadora (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modalidade unificado.tipo_modalidade_banca,
    titulo_trabalho TEXT,
    ano INTEGER,
    curso TEXT,
    descricao TEXT,
    id_instituicao BIGINT REFERENCES unificado.organizacao(id),
    id_candidato BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id)
