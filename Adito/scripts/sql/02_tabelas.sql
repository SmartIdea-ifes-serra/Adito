-- Classe AtuacaoProfissional
CREATE TABLE unificado.atuacao_profissional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_inicio INTEGER,
    ano_fim INTEGER,
    atual BOOLEAN,
    vinculo TEXT,
    enquadramento TEXT,
    regime_trabalho TEXT,
    atividades TEXT,
    id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE,
    id_instituicao BIGINT NOT NULL REFERENCES unificado.instituicao_lattes(id)
);

-- Classe OrientacaoLattes
CREATE TABLE unificado.orientacao_lattes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
