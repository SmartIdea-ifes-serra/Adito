    ano INTEGER
);

-- ----------------------------------------------------------------------------
-- 8. PRODUCAO CIENTIFICA E HIERARQUIA DE PRODUCOES
-- ----------------------------------------------------------------------------

-- Classe Producao (Superclasse abstrata)
CREATE TABLE unificado.producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    ano INTEGER
);

-- Subclasse ArtigoTrabalhoEvento -> Producao
CREATE TABLE unificado.artigo_trabalho_evento (
    id BIGINT PRIMARY KEY REFERENCES unificado.producao(id) ON DELETE CASCADE,
    id_tipo_publicacao BIGINT REFERENCES unificado.tipo_artigo_evento(id),
    veiculo_revista_evento TEXT,
    doi TEXT,
    issn_isbn TEXT,
    volume TEXT,
    numero TEXT,
    paginas TEXT,
    data_publicacao TEXT,
    natureza TEXT
);

-- Subclasse LivroCapitulo -> Producao
CREATE TABLE unificado.livro_capitulo (
    id BIGINT PRIMARY KEY REFERENCES unificado.producao(id) ON DELETE CASCADE,
    id_tipo_livro_capitulo BIGINT REFERENCES unificado.tipo_livro_capitulo(id),
    editora TEXT,
    paginas TEXT
);

-- Subclasse ProducaoTecnicaArtisticaBibliografica -> Producao
CREATE TABLE unificado.producao_tecnica_artistica_bibliografica (
    id BIGINT PRIMARY KEY REFERENCES unificado.producao(id) ON DELETE CASCADE,
    id_categoria BIGINT REFERENCES unificado.categoria_producao_tecnica(id),
    subtipo TEXT
);

-- Subclasse PatenteRegistro -> Producao
CREATE TABLE unificado.patente_registro (
    id BIGINT PRIMARY KEY REFERENCES unificado.producao(id) ON DELETE CASCADE,
    id_tipo_patente_registro BIGINT REFERENCES unificado.tipo_patente_registro(id),
    modalidade_patente TEXT,
    pais TEXT,
    data_registro TEXT,
    codigo_registro TEXT,
    id_instituicao_depositante BIGINT NOT NULL REFERENCES unificado.organizacao(id)
);

-- Classe PremioTitulo
CREATE TABLE unificado.premio_titulo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao_titulo TEXT NOT NULL,
    ano INTEGER,
    id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE
);
