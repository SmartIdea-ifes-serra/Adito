SET search_path TO unificado, public;

-- ----------------------------------------------------------------------------
-- 1. ESTRUTURA ORGANIZACIONAL E LOCALIZACAO
-- ----------------------------------------------------------------------------

-- Classe Organizacao (Superclasse)
CREATE TABLE unificado.organizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    id_tipo_organizacao BIGINT REFERENCES unificado.tipo_organizacao(id),
    id_organizacao_pai BIGINT REFERENCES unificado.organizacao(id)
);

-- Subclasse InstituicaoLattes -> Organizacao
CREATE TABLE unificado.instituicao_lattes (
    id BIGINT PRIMARY KEY REFERENCES unificado.organizacao(id) ON DELETE CASCADE,
    sigla TEXT,
    pais TEXT
);

-- Subclasse InstituicaoParceiraCNPQ -> Organizacao
CREATE TABLE unificado.instituicao_parceira_cnpq (
    id BIGINT PRIMARY KEY REFERENCES unificado.organizacao(id) ON DELETE CASCADE,
    sigla TEXT,
    uf unificado.tipo_uf
);

-- Classe Endereco
CREATE TABLE unificado.endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logradouro TEXT,
    numero TEXT,
    complemento TEXT,
    bairro TEXT,
    localidade TEXT,
    uf unificado.tipo_uf,
    cep TEXT,
    caixa_postal TEXT,
    latitude TEXT,
    longitude TEXT
);

-- ----------------------------------------------------------------------------
-- 2. AREAS DE CONHECIMENTO E IDIOMAS
-- ----------------------------------------------------------------------------

-- Classe GrandeArea
CREATE TABLE unificado.grande_area (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Classe AreaConhecimento
CREATE TABLE unificado.area_conhecimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    id_grande_area BIGINT REFERENCES unificado.grande_area(id)
);

-- Classe SubareaConhecimentoLattes
CREATE TABLE unificado.subarea_conhecimento_lattes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    id_area_conhecimento BIGINT NOT NULL REFERENCES unificado.area_conhecimento(id)
);

-- Classe EspecialidadeLattes
CREATE TABLE unificado.especialidade_lattes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    id_subarea_conhecimento BIGINT NOT NULL REFERENCES unificado.subarea_conhecimento_lattes(id)
);

-- Classe AreaAtuacao (ligada a GrandeArea [1], PessoaLattes [1])
CREATE TABLE unificado.area_atuacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area TEXT,
    subarea TEXT,
    especialidade TEXT,
    id_grande_area BIGINT NOT NULL REFERENCES unificado.grande_area(id)
    -- id_pessoa_lattes sera adicionado apos criacao de pessoa_lattes
);

-- Classe Idioma
CREATE TABLE unificado.idioma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_idioma TEXT NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. PESSOAS E HIERARQUIA DE PESSOAS
-- ----------------------------------------------------------------------------

-- Classe Pessoa (Superclasse)
CREATE TABLE unificado.pessoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Subclasse PessoaLattes -> Pessoa
CREATE TABLE unificado.pessoa_lattes (
    id BIGINT PRIMARY KEY REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_lattes TEXT,
    nome_citacoes TEXT,
    texto_resumo TEXT,
    bolsa_produtividade TEXT,
    endereco_profissional TEXT,
    url_lattes TEXT,
    data_atualizacao_cv DATE
);

-- Subclasse PessoaSRC -> Pessoa
CREATE TABLE unificado.pessoa_src (
    id BIGINT PRIMARY KEY REFERENCES unificado.pessoa(id) ON DELETE CASCADE
);

-- Subclasse Pesquisador -> Pessoa
CREATE TABLE unificado.pesquisador (
    id BIGINT PRIMARY KEY REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_titulacao BIGINT, -- FK para titulacao
    id_organizacao BIGINT REFERENCES unificado.organizacao(id)
);

-- Subclasse Estudante -> Pessoa
CREATE TABLE unificado.estudante (
    id BIGINT PRIMARY KEY REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_campus BIGINT REFERENCES unificado.organizacao(id),
    id_nivel_treinamento BIGINT REFERENCES unificado.nivel_treinamento(id),
    id_curso BIGINT -- FK para curso
);

-- Ajusta FK de AreaAtuacao para PessoaLattes
ALTER TABLE unificado.area_atuacao
    ADD COLUMN id_pessoa_lattes BIGINT NOT NULL REFERENCES unificado.pessoa_lattes(id) ON DELETE CASCADE;

-- Classe Titulacao
CREATE TABLE unificado.titulacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- FK de Pesquisador para Titulacao
ALTER TABLE unificado.pesquisador
    ADD CONSTRAINT fk_pesquisador_titulacao FOREIGN KEY (id_titulacao) REFERENCES unificado.titulacao(id);

-- Classe Curso
CREATE TABLE unificado.curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- FK de Estudante para Curso
ALTER TABLE unificado.estudante
    ADD CONSTRAINT fk_estudante_curso FOREIGN KEY (id_curso) REFERENCES unificado.curso(id);

-- ----------------------------------------------------------------------------
-- 4. GRUPOS DE PESQUISA, LINHAS E INFRAESTRUTURA
-- ----------------------------------------------------------------------------

-- Classe GrupoPesquisa (Superclasse)
CREATE TABLE unificado.grupo_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    sigla TEXT,
    url_cnpq TEXT,
    id_organizacao BIGINT NOT NULL REFERENCES unificado.organizacao(id),
    id_area_conhecimento BIGINT NOT NULL REFERENCES unificado.area_conhecimento(id)
);

-- Subclasse GrupoPesquisaCNPQ -> GrupoPesquisa
CREATE TABLE unificado.grupo_pesquisa_cnpq (
    id BIGINT PRIMARY KEY REFERENCES unificado.grupo_pesquisa(id) ON DELETE CASCADE,
    situacao_grupo unificado.tipo_situacao_grupo,
    ano_formacao INTEGER,
    data_situacao DATE,
    data_ultimo_envio DATE,
    repercussoes TEXT,
    id_endereco BIGINT REFERENCES unificado.endereco(id),
    id_instituicao BIGINT NOT NULL REFERENCES unificado.organizacao(id),
    id_campus BIGINT NOT NULL REFERENCES unificado.organizacao(id)
);

-- Classe GrupoPesquisaExterno
CREATE TABLE unificado.grupo_pesquisa_externo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Classe LinhaPesquisa
CREATE TABLE unificado.linha_pesquisa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT NOT NULL
);

-- Classe EquipamentoSoftware
CREATE TABLE unificado.equipamento_software (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    tipo unificado.tipo_infraestrutura
);

-- Comunicacoes do GrupoPesquisaCNPQ
CREATE TABLE unificado.telefone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE
);

CREATE TABLE unificado.fax (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT NOT NULL,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE
);

CREATE TABLE unificado.website (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE
);

-- Email de contato do GrupoPesquisaCNPQ (e-mail de pessoa não é guardado: LGPD)
CREATE TABLE unificado.email (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco TEXT NOT NULL,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 5. MEMBROS DE GRUPO
-- ----------------------------------------------------------------------------

-- Classe Papel
CREATE TABLE unificado.papel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Classe MembroGrupo (Superclasse)
CREATE TABLE unificado.membro_grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio DATE,
    data_fim DATE,
    id_papel BIGINT REFERENCES unificado.papel(id)
);

-- Subclasse MembroGrupoCNPQ -> MembroGrupo
CREATE TABLE unificado.membro_grupo_cnpq (
    id BIGINT PRIMARY KEY REFERENCES unificado.membro_grupo(id) ON DELETE CASCADE,
    status_participacao unificado.tipo_status_participacao,
    id_pessoa BIGINT NOT NULL REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_grupo_pesquisa_cnpq BIGINT NOT NULL REFERENCES unificado.grupo_pesquisa_cnpq(id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 6. INICIATIVAS, ACOES, PROJETOS E ATIVIDADES
-- ----------------------------------------------------------------------------

-- Classe Iniciativa (Superclasse)
CREATE TABLE unificado.iniciativa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Subclasse Acao -> Iniciativa
CREATE TABLE unificado.acao (
    id BIGINT PRIMARY KEY REFERENCES unificado.iniciativa(id) ON DELETE CASCADE,
    id_origem INTEGER, -- ID original do SRC
    processo TEXT,
    data_cadastro DATE,
    relatorio_aprovado BOOLEAN,
    url_detalhe TEXT,
    id_natureza BIGINT REFERENCES unificado.natureza(id),
    id_tipo_acao BIGINT REFERENCES unificado.tipo_acao(id),
    id_acao_pai BIGINT REFERENCES unificado.acao(id),
    id_area_conhecimento BIGINT REFERENCES unificado.area_conhecimento(id),
    id_coordenador BIGINT REFERENCES unificado.pessoa(id)
);

-- Classe TipoAtividade
CREATE TABLE unificado.tipo_atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

-- Classe Atividade (Composicao com Acao: Acao ◆ Atividade)
CREATE TABLE unificado.atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    id_acao BIGINT NOT NULL REFERENCES unificado.acao(id) ON DELETE CASCADE,
    id_tipo_atividade BIGINT REFERENCES unificado.tipo_atividade(id)
);

-- Subclasse MembroEquipeExecucaoSRC -> MembroGrupo
CREATE TABLE unificado.membro_equipe_execucao_src (
    id BIGINT PRIMARY KEY REFERENCES unificado.membro_grupo(id) ON DELETE CASCADE,
    id_atividade BIGINT NOT NULL REFERENCES unificado.atividade(id) ON DELETE CASCADE,
    id_pessoa BIGINT NOT NULL REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_vinculo BIGINT REFERENCES unificado.vinculo(id)
);

-- Classe RegistroParticipante
CREATE TABLE unificado.registro_participante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_horaria NUMERIC(8,2),
    certificado BOOLEAN,
    data_inicio DATE,
    data_termino DATE,
    id_atividade BIGINT NOT NULL REFERENCES unificado.atividade(id) ON DELETE CASCADE,
    id_pessoa BIGINT NOT NULL REFERENCES unificado.pessoa(id) ON DELETE CASCADE,
    id_situacao BIGINT REFERENCES unificado.situacao_participante(id)
);

-- Subclasse ProjetoPesquisa -> Iniciativa
CREATE TABLE unificado.projeto_pesquisa (
    id BIGINT PRIMARY KEY REFERENCES unificado.iniciativa(id) ON DELETE CASCADE,
    id_origem INTEGER, -- ID original do SigPesq
    data_inicio DATE,
    data_fim DATE,
    palavras_chave TEXT,
    sigilo BOOLEAN,
    id_natureza_projeto unificado.tipo_natureza_projeto,
    parecer_diretoria unificado.tipo_parecer_diretoria,
    id_campus BIGINT REFERENCES unificado.organizacao(id),
    id_area_conhecimento BIGINT REFERENCES unificado.area_conhecimento(id),
    id_coordenador BIGINT REFERENCES unificado.pesquisador(id)
);

-- Subclasse ProjetoLATTES -> Iniciativa
CREATE TABLE unificado.projeto_lattes (
    id BIGINT PRIMARY KEY REFERENCES unificado.iniciativa(id) ON DELETE CASCADE,
    ano_inicio INTEGER,
    ano_conclusao INTEGER,
    situacao unificado.tipo_status_ciclo,
    descricao TEXT
);

-- Classe edital
CREATE TABLE unificado.edital (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL
);

-- Classe PlanoTrabalho
CREATE TABLE unificado.plano_trabalho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo INTEGER,
    titulo TEXT NOT NULL,
    id_projeto_pesquisa BIGINT NOT NULL REFERENCES unificado.projeto_pesquisa(id) ON DELETE CASCADE,
    id_edital BIGINT REFERENCES unificado.edital(id),
    id_area_conhecimento BIGINT REFERENCES unificado.area_conhecimento(id)
);

-- Classe Orientacao
CREATE TABLE unificado.orientacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem INTEGER, -- ID original do SigPesq
    ano INTEGER,
    valor_bolsa NUMERIC(12,2),
    data_inicio DATE,
    data_fim DATE,
    cancelado BOOLEAN,
    nome_cancelador TEXT,
    data_cancelado DATE,
    relatorio_enviado BOOLEAN,
    modalidade unificado.tipo_modalidade,
    gerenciamento unificado.tipo_gerenciamento,
    id_programa BIGINT REFERENCES unificado.programa(id),
    id_plano_trabalho BIGINT NOT NULL REFERENCES unificado.plano_trabalho(id) ON DELETE CASCADE,
    id_orientador BIGINT NOT NULL REFERENCES unificado.pesquisador(id),
    id_orientado BIGINT NOT NULL REFERENCES unificado.estudante(id),
    id_campus BIGINT REFERENCES unificado.organizacao(id),
    id_financiador BIGINT REFERENCES unificado.organizacao(id)
);

