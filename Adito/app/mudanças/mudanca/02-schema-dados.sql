-- ==========================
-- DIM_TEMPO
-- ==========================
CREATE TABLE dim_tempo (
    id_tempo INT PRIMARY KEY,
    dia DATE,
    semana INT,
    mes INT,
    trimestre INT,
    ano INT
);

-- ==========================
-- DIM_PRODUTO
-- ==========================
CREATE TABLE dim_produto (
    id_produto INT PRIMARY KEY,
    produto VARCHAR(100),
    categoria VARCHAR(100),
    segmento VARCHAR(100)
);

-- ==========================
-- DIM_CLIENTE
-- ==========================
CREATE TABLE dim_cliente (
    id_cliente INT PRIMARY KEY,
    cliente VARCHAR(150),
    porte VARCHAR(50),
    setor VARCHAR(100)
);

-- ==========================
-- DIM_REGIAO
-- ==========================
CREATE TABLE dim_regiao (
    id_regiao INT PRIMARY KEY,
    cidade VARCHAR(100),
    estado CHAR(2),
    regiao VARCHAR(50)
);

-- ==========================
-- DIM_CANAL
-- ==========================
CREATE TABLE dim_canal (
    id_canal INT PRIMARY KEY,
    canal VARCHAR(100)
);

-- ==========================
-- DIM_VENDEDOR
-- ==========================
CREATE TABLE dim_vendedor (
    id_vendedor INT PRIMARY KEY,
    nome VARCHAR(100),
    equipe VARCHAR(100),
    regiao_atuacao VARCHAR(50)
);

-- ==========================
-- FACT_VENDAS
-- ==========================
CREATE TABLE fact_vendas (
    id_venda INT PRIMARY KEY,

    id_tempo INT,
    id_produto INT,
    id_cliente INT,
    id_regiao INT,
    id_canal INT,
    id_vendedor INT,

    quantidade_vendida INT,
    valor_bruto DECIMAL(12,2),
    desconto DECIMAL(12,2),
    receita_liquida DECIMAL(12,2),
    custo DECIMAL(12,2),
    lucro DECIMAL(12,2),

    FOREIGN KEY (id_tempo) REFERENCES dim_tempo(id_tempo),
    FOREIGN KEY (id_produto) REFERENCES dim_produto(id_produto),
    FOREIGN KEY (id_cliente) REFERENCES dim_cliente(id_cliente),
    FOREIGN KEY (id_regiao) REFERENCES dim_regiao(id_regiao),
    FOREIGN KEY (id_canal) REFERENCES dim_canal(id_canal),
    FOREIGN KEY (id_vendedor) REFERENCES dim_vendedor(id_vendedor)
);

